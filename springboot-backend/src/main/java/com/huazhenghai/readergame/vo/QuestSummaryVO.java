package com.huazhenghai.readergame.vo;

public class QuestSummaryVO {
    private int dailyTotal;
    private int dailyCompleted;
    private int dailyClaimable;
    private int weeklyTotal;
    private int weeklyCompleted;
    private int weeklyClaimable;
    private int achievementClaimable;

    public int getDailyTotal() { return dailyTotal; }
    public void setDailyTotal(int dailyTotal) { this.dailyTotal = dailyTotal; }
    public int getDailyCompleted() { return dailyCompleted; }
    public void setDailyCompleted(int dailyCompleted) { this.dailyCompleted = dailyCompleted; }
    public int getDailyClaimable() { return dailyClaimable; }
    public void setDailyClaimable(int dailyClaimable) { this.dailyClaimable = dailyClaimable; }
    public int getWeeklyTotal() { return weeklyTotal; }
    public void setWeeklyTotal(int weeklyTotal) { this.weeklyTotal = weeklyTotal; }
    public int getWeeklyCompleted() { return weeklyCompleted; }
    public void setWeeklyCompleted(int weeklyCompleted) { this.weeklyCompleted = weeklyCompleted; }
    public int getWeeklyClaimable() { return weeklyClaimable; }
    public void setWeeklyClaimable(int weeklyClaimable) { this.weeklyClaimable = weeklyClaimable; }
    public int getAchievementClaimable() { return achievementClaimable; }
    public void setAchievementClaimable(int achievementClaimable) { this.achievementClaimable = achievementClaimable; }
}
