package com.huazhenghai.readergame.vo;

public class WorldlineSummaryVO {

    private double worldlineShift;
    private double starstreamAttention;
    private double scenarioPressure;
    private int dangerLevel;

    public double getWorldlineShift() { return worldlineShift; }
    public void setWorldlineShift(double worldlineShift) { this.worldlineShift = worldlineShift; }
    public double getStarstreamAttention() { return starstreamAttention; }
    public void setStarstreamAttention(double starstreamAttention) { this.starstreamAttention = starstreamAttention; }
    public double getScenarioPressure() { return scenarioPressure; }
    public void setScenarioPressure(double scenarioPressure) { this.scenarioPressure = scenarioPressure; }
    public int getDangerLevel() { return dangerLevel; }
    public void setDangerLevel(int dangerLevel) { this.dangerLevel = dangerLevel; }
}
